// The banner's backdrop: a wall of type from one hand-picked list of terms.
// The list is chosen, not derived -- it is close to the Career page's skills
// but a separate thing, so editing one does not change the other.
//
// The field is 2560 units wide against a 96-unit height, sliced centred,
// so the scale comes from the height and never the width. Both ends fade; the
// banner's mask does that.
//
// Nothing overlaps, nothing is clipped, and nothing is too faint to read, and
// all three are arithmetic rather than luck:
//
//   - widths were measured from the real Inter at 100px and scaled, so words
//     are laid end to end with a gap of 10.4 to 22.1 units;
//   - rows are 16.08 apart, further than the tallest word is high (15.60),
//     and baselines are bounded by the font's true ink (0.875em up, 0.286em
//     down, rounded to 0.9 and 0.3);
//   - every word's colour is composited over the gradient at its own position
//     and checked: none reads at less than 1.8:1 against the background it
//     sits on. Black is used only where the gradient has brightened enough to
//     carry it -- on the dark end it cannot reach even 2:1 at full opacity.
//
// Generated once with a fixed seed and written down: the positions must be
// identical in the prerendered HTML and in the hydrated page, and a list of
// numbers cannot drift between them. Terms are dealt from a shuffled deck, so
// every one appears before any appears twice.
//
// Decorative only. The banner marks the whole svg aria-hidden, so none of this
// is read out or indexed as content; the readable list is on the Career page.
